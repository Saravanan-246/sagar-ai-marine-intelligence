"""
Repair Candidates Router.
Stores and retrieves repair options generated by the engine for a decision.
"""

from typing import List

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.models import Decision, RepairCandidate
from app.schemas import RepairCandidateCreate, RepairCandidateOut

router = APIRouter()


async def _get_decision_or_404(db: AsyncSession, decision_id: str) -> Decision:
    result = await db.execute(select(Decision).where(Decision.id == decision_id))
    d = result.scalar_one_or_none()
    if not d:
        raise HTTPException(status_code=404, detail=f"Decision '{decision_id}' not found.")
    return d


@router.get("/{decision_id}", response_model=List[RepairCandidateOut])
async def list_repair_candidates(
    decision_id: str,
    db: AsyncSession = Depends(get_db),
):
    """List all repair candidates for a decision, ordered by score descending."""
    await _get_decision_or_404(db, decision_id)
    result = await db.execute(
        select(RepairCandidate)
        .where(RepairCandidate.decision_id == decision_id)
        .order_by(RepairCandidate.score.desc())
    )
    return result.scalars().all()


@router.post(
    "/{decision_id}",
    response_model=RepairCandidateOut,
    status_code=status.HTTP_201_CREATED,
)
async def add_repair_candidate(
    decision_id: str,
    payload: RepairCandidateCreate,
    db: AsyncSession = Depends(get_db),
):
    """Register a new repair candidate against a decision."""
    await _get_decision_or_404(db, decision_id)

    candidate = RepairCandidate(
        id=payload.id,
        decision_id=decision_id,
        tier=payload.tier,
        title=payload.title,
        description=payload.description,
        plan_churn=payload.plan_churn,
        preservation_ratio=payload.preservation_ratio,
        tradeoffs=payload.tradeoffs,
        feasibility=payload.feasibility,
        score=payload.score,
        recommendation_reason=payload.recommendation_reason,
        linked_event_id=payload.linked_event_id,
    )
    candidate.what_changes = payload.what_changes
    candidate.what_remains_unchanged = payload.what_remains_unchanged

    db.add(candidate)
    await db.commit()
    await db.refresh(candidate)
    return candidate


@router.get("/{decision_id}/{candidate_id}", response_model=RepairCandidateOut)
async def get_repair_candidate(
    decision_id: str,
    candidate_id: str,
    db: AsyncSession = Depends(get_db),
):
    result = await db.execute(
        select(RepairCandidate)
        .where(
            RepairCandidate.decision_id == decision_id,
            RepairCandidate.id == candidate_id,
        )
    )
    candidate = result.scalar_one_or_none()
    if not candidate:
        raise HTTPException(
            status_code=404,
            detail=f"Candidate '{candidate_id}' not found for decision '{decision_id}'.",
        )
    return candidate
